// Package menu generates the boot menu configuration. The menu is executed by
// an unmodified, vendor-signed GRUB (taken from one of the user's own images),
// so this file is the only boot-time logic quiver itself contributes. It is
// plain text and deliberately small enough to audit by eye.
package menu

import (
	"crypto/pbkdf2"
	"crypto/rand"
	"crypto/sha512"
	"encoding/hex"
	"fmt"
	"strings"
)

// Entry is one bootable image.
type Entry struct {
	Title  string
	Slot   int    // GPT partition number, used as a stable menu id
	FSUUID string // GRUB form, e.g. "1a2b-3c4d"
	Loader string // path on that partition, e.g. /EFI/BOOT/BOOTX64.EFI
	// Unsigned marks a loader without a valid signature. Its title gets a
	// note that depends on the Secure Boot state detected at boot time.
	Unsigned bool
}

// Options control menu behaviour.
type Options struct {
	Timeout      int    // seconds; -1 waits forever
	DefaultSlot  int    // slot of the entry booted when the timeout expires (0 = first)
	User         string // superuser name when a password is set
	PasswordHash string // grub.pbkdf2.sha512.* hash; empty = no password
	Version      string
}

// Config renders grub.cfg.
//
// Signed GRUB sets $lockdown to "y" when Secure Boot is enforcing (verified
// under OVMF with Secure Boot on and off). The menu uses it to show the
// Secure Boot state as its first entry and to tell, per unsigned image,
// whether it can boot right now.
func Config(entries []Entry, o Options) string {
	var b strings.Builder
	w := func(f string, a ...any) { fmt.Fprintf(&b, f, a...) }
	w("# Boot menu generated by quiver %s.\n", o.Version)
	w("# Each entry hands control to the image's own UEFI loader on its own\n")
	w("# partition. With Secure Boot on, shim and the firmware verify every\n")
	w("# chainloaded binary. Regenerate with `quiver menu`.\n\n")
	def := "slot0"
	for _, e := range entries {
		if def == "slot0" || e.Slot == o.DefaultSlot {
			def = fmt.Sprintf("slot%d", e.Slot)
		}
		if e.Slot == o.DefaultSlot {
			break
		}
	}
	w("set default=%s\n", quote(def))
	w("set timeout=%d\n", o.Timeout)
	w("set timeout_style=menu\n")
	w("set menu_color_normal=light-gray/black\n")
	w("set menu_color_highlight=black/yellow\n")
	w("set color_normal=light-gray/black\n\n")
	w("if [ \"$lockdown\" = \"y\" ]; then\n")
	w("\tset qv_sb='Secure Boot: ON   -  signed images only  (select: firmware settings)'\n")
	w("\tset qv_unsigned='unsigned: blocked while Secure Boot is on'\n")
	w("else\n")
	w("\tset qv_sb='Secure Boot: OFF  -  all images can boot  (select: firmware settings)'\n")
	w("\tset qv_unsigned='unsigned: OK, Secure Boot is off'\n")
	w("fi\n\n")
	restricted := ""
	if o.PasswordHash != "" {
		w("set superusers=%s\n", quote(o.User))
		w("password_pbkdf2 %s %s\n\n", quote(o.User), o.PasswordHash)
	} else {
		restricted = " --unrestricted"
	}
	w("menuentry \"$qv_sb\" --id sbstate --unrestricted {\n\tfwsetup\n}\n\n")
	for _, e := range entries {
		title := quote(e.Title)
		if e.Unsigned {
			title += `"  [$qv_unsigned]"` // double quotes: expanded when the menu is built
		}
		w("menuentry %s --id %s%s {\n", title, quote(fmt.Sprintf("slot%d", e.Slot)), restricted)
		w("\tsearch --no-floppy --fs-uuid --set=root %s\n", e.FSUUID)
		w("\tchainloader %s\n", e.Loader)
		w("}\n\n")
	}
	w("menuentry 'Reboot' --id reboot --unrestricted {\n\treboot\n}\n")
	w("menuentry 'Power off' --id poweroff --unrestricted {\n\thalt\n}\n")
	return b.String()
}

// quote makes s a single GRUB word using single quotes.
func quote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

// Iterations is the PBKDF2 work factor for menu passwords. The hash is stored
// on the stick, so it is set well above grub-mkpasswd-pbkdf2's default.
const Iterations = 100000

// HashPassword returns a GRUB password_pbkdf2 hash (PBKDF2-HMAC-SHA512).
func HashPassword(password string) (string, error) {
	if len(password) < 8 {
		return "", fmt.Errorf("menu password must be at least 8 characters")
	}
	salt := make([]byte, 64)
	if _, err := rand.Read(salt); err != nil {
		return "", err
	}
	key, err := pbkdf2.Key(sha512.New, password, salt, Iterations, 64)
	if err != nil {
		return "", err
	}
	return fmt.Sprintf("grub.pbkdf2.sha512.%d.%s.%s", Iterations,
		strings.ToUpper(hex.EncodeToString(salt)), strings.ToUpper(hex.EncodeToString(key))), nil
}

// ValidUser reports whether name is a safe GRUB superuser name.
func ValidUser(name string) bool {
	if name == "" || len(name) > 32 {
		return false
	}
	for _, r := range name {
		if !(r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' || r == '_' || r == '-') {
			return false
		}
	}
	return true
}
